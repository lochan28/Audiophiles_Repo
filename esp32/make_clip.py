"""Turn a WAV file into clip.h, so the transmitter ESP32 can carry it.

The transmitter has no microphone yet, so for the first radio test it plays a
recording that is baked into its flash memory. This script does the baking:
it reads a WAV, converts it to what the receiver's built-in DAC can play
(mono, 8-bit, SAMPLE_RATE), and writes it out as a C array.

Run it with the project's venv:

    .venv\\Scripts\\python.exe esp32\\make_clip.py  some_file.wav

It writes esp32/tx_clip/clip.h. Then open tx_clip.ino in the Arduino IDE and
upload it. Nothing else in the project reads or writes this file.
"""

import sys
from pathlib import Path

import numpy as np
import soundfile as sf
from scipy.signal import resample_poly

# ============================================================================
# TUNABLE -- safe to change
# ============================================================================

# Sample rate the clip is stored and played at. 16000 matches our model.
# Lower (8000) = half the size and half the radio traffic, but duller sound.
# If you change this, nothing else needs changing: the rate travels inside
# clip.h and the transmitter tells the receiver.
SAMPLE_RATE = 16000

# How many seconds of the WAV to keep. The receiver stores the whole clip in
# RAM before playing, and it has room for MAX_SECONDS_ON_RECEIVER (see
# rx_clip.ino). 3 s at 16 kHz is 48 KB -- comfortable.
SECONDS = 3.0

# Where in the WAV to start, in seconds. Move it if the start is silence.
START_AT = 0.0

# Peak level after normalising, 0..1. 0.9 uses almost the whole 8-bit range
# (loudest and least hiss) while leaving a little headroom against clipping.
PEAK = 0.9

# ============================================================================
# FIXED -- the receiver depends on these
# ============================================================================

# The ESP32's built-in DAC is 8-bit and unsigned: 0 = lowest, 128 = silence,
# 255 = highest. That is the only format rx_clip.ino knows how to play.
DAC_MIDPOINT = 128

OUT_PATH = Path(__file__).parent / "tx_clip" / "clip.h"


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: make_clip.py  input.wav")
    src = Path(sys.argv[1])

    audio, rate = sf.read(src, dtype="float32", always_2d=True)
    audio = audio.mean(axis=1)                        # stereo -> mono

    if rate != SAMPLE_RATE:                           # e.g. 48 kHz -> 16 kHz
        g = np.gcd(rate, SAMPLE_RATE)
        audio = resample_poly(audio, SAMPLE_RATE // g, rate // g)

    start = int(START_AT * SAMPLE_RATE)
    audio = audio[start:start + int(SECONDS * SAMPLE_RATE)]
    if len(audio) == 0:
        sys.exit(f"nothing left after START_AT={START_AT}s -- the WAV is shorter")

    peak = np.abs(audio).max()
    if peak == 0:
        sys.exit("the selected part is pure silence")
    audio = audio / peak * PEAK

    # -1..+1  ->  0..255 with silence at 128
    samples = np.clip(np.round(audio * 127) + DAC_MIDPOINT, 0, 255).astype(np.uint8)

    rows = [", ".join(str(v) for v in samples[i:i + 20])
            for i in range(0, len(samples), 20)]
    OUT_PATH.parent.mkdir(exist_ok=True)
    OUT_PATH.write_text(
        f"// Generated by make_clip.py from {src.name} -- do not edit by hand.\n"
        f"// {len(samples)} samples = {len(samples) / SAMPLE_RATE:.2f} s, "
        f"8-bit unsigned, 128 = silence.\n"
        f"#pragma once\n"
        f"#include <stdint.h>\n\n"
        f"const uint32_t CLIP_RATE = {SAMPLE_RATE};\n"
        f"const uint32_t CLIP_LEN  = {len(samples)};\n"
        f"const uint8_t  CLIP[] = {{\n  " + ",\n  ".join(rows) + "\n};\n",
        encoding="ascii",
    )
    print(f"{src.name}: {rate} Hz -> {SAMPLE_RATE} Hz, "
          f"{len(samples)} samples ({len(samples) / SAMPLE_RATE:.2f} s, "
          f"{len(samples) / 1024:.1f} KB) -> {OUT_PATH}")


if __name__ == "__main__":
    main()
